-- ---------------------------------------------------------------------------
-- Prestations génériques antérieures sur les modèles couverts par le PDF
--
-- Le catalogue du client fait foi pour ces treize modèles. Les prestations
-- créées avant l'import et absentes du document (donc sans catégorie) sont
-- désactivées pour ne pas doubler la liste côté client. Rien n'est supprimé :
-- elles restent visibles dans le back-office et se réactivent d'une case à
-- cocher. Le diagnostic reste actif, il n'a pas d'équivalent dans le PDF.
-- ---------------------------------------------------------------------------
update public.repairs r
   set is_active = false, updated_at = now()
  from public.console_models m
 where m.id = r.model_id
   and m.slug in ('ps4', 'ps4-slim', 'ps4-pro', 'switch', 'switch-v2', 'switch-lite', 'switch-oled',
                  'switch-2', 'xbox-one', 'xbox-one-s', 'xbox-one-x', 'xbox-series-s', 'xbox-series-x')
   and r.category_id is null
   and not r.is_diagnostic_only
   and r.is_active;

