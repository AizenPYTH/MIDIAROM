-- État des lieux (lecture seule) — dernier résultat affiché par le SQL Editor.
-- ---------------------------------------------------------------------------
select element, nombre from (
  select  1, 'modèles de console', count(*) from public.console_models
  union all select  2, 'catégories de réparation', count(*) from public.repair_categories
  union all select  3, 'prestations rattachées à une catégorie', count(*) from public.repairs where category_id is not null
  union all select  4, 'prestations au tarif à configurer', count(*) from public.repairs where price_is_provisional
) as etat (ordre, element, nombre)
order by ordre;
