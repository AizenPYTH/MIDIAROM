insert into public.repairs (model_id, fault_id, category_id, name, slug, price_cents, price_is_provisional, display_order, is_active)
select m.id, f.id, rc.id, s.name, s.slug, 0, true, s.display_order, true
  from source s
  join public.console_models m on m.slug = s.model_slug
  join public.faults f on f.slug = s.fault_slug
  join public.repair_categories rc on rc.slug = s.category_slug
on conflict (model_id, fault_id) do update
   set category_id = excluded.category_id,
       -- La formulation du PDF fait foi ; le prix, le résumé et l'activation
       -- saisis dans le back-office sont conservés. Un renommage manuel serait
       -- donc écrasé au prochain rejeu de ce fichier.
       name = excluded.name,
       display_order = case when public.repairs.price_is_provisional then excluded.display_order else public.repairs.display_order end,
       updated_at = now();

